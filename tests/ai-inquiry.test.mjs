import assert from 'node:assert/strict';
import {recommend,needLabels} from '../lib/sales.mjs';
import {encodeHandoff,decodeHandoff} from '../lib/handoff.mjs';
import {buildInquiry,validateInquiry} from '../lib/inquiry.mjs';
const base={industry:'hospitality',locations:'one',timing:'quarter',support:'remote'};
const answers={...base,needs:['ai','training','displays']};
const r=recommend(answers);
assert.equal(r.primary,'ai');
assert.ok(r.additions.some(x=>x.includes('Staff Technology Confidence')));
assert.ok(r.additions.some(x=>x.includes('Display')));
assert.equal(recommend({...base,needs:['clarity','ai']}).primary,'review');
assert.ok(recommend({...base,needs:['clarity','ai']}).additions.some(x=>x.includes('AI Workflow')));
assert.deepEqual(decodeHandoff(encodeHandoff({...base,needs:Object.keys(needLabels)})),{...base,needs:Object.keys(needLabels)});
const f={...base,name:'Workflow Buyer',company:'Sample Business',email:'buyer@example.test',offer:'ai',consent:true,message:'Summarize incoming inquiries for human review.'};
assert.deepEqual(validateInquiry(f),{});
const payload=buildInquiry(f,answers);
assert.equal(payload.requestType,'Other commercial technology request');
assert.match(payload.requirements,/Selected offer: AI Workflow Integration/);
assert.match(payload.requirements,/RECOMMENDED START: AI Workflow Integration/);
assert.match(payload.requirements,/human review/);
console.log('AI recommendation, combined needs, inquiry validation and payload checks passed.');
